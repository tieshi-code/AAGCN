class Feeder_Augmented(torch.utils.data.Dataset):
    """ 增强版 Feeder for skeleton-based action recognition
    包含多种数据增强方法：
    - 随机旋转（Random Rotation）
    - 随机缩放（Random Scaling）
    - 随机平移（Random Translation）
    - 时间抖动（Temporal Jitter）
    - 关节噪声（Gaussian Noise）
    - 左右镜像翻转（Mirror Flip）
    - 骨架遮挡/丢弃（Drop Joint/Bone）
    - 混合增强（Mixup/CutMix for skeleton）
    
    Arguments:
        data_path: the path to '.npy' data, the shape of data should be (N, C, T, V, M)
        label_path: the path to label
        random_choose: If true, randomly choose a portion of the input sequence
        random_move: If true, randomly pad zeros at the begining or end of sequence
        window_size: The length of the output sequence
        normalization: If true, normalize input sequence
        debug: If true, only use the first 100 samples
        layout: 'openpose' or 'alphapose'
        
        # 增强参数
        aug_prob: 整体增强概率 (0.5-0.8)
        rotation_range: 旋转角度范围 (-30, 30)
        scale_range: 缩放范围 (0.8, 1.2)
        translate_range: 平移范围 (-0.2, 0.2)
        temporal_jitter_ratio: 时间抖动比例 0.15
        noise_sigma: 高斯噪声标准差 0.03
        drop_joint_ratio: 关节丢弃比例 0.2
        use_mixup: 是否使用Mixup增强
        mixup_alpha: Mixup alpha参数
    """

    def __init__(self,
                 data_path,
                 label_path,
                 random_choose=False,
                 random_move=False,
                 window_size=-1,
                 debug=False,
                 mmap=True,
                 layout='alphapose',
                 # 增强参数
                 aug_prob=0.7,
                 rotation_range=(-25, 25),
                 scale_range=(0.85, 1.15),
                 translate_range=(-0.15, 0.15),
                 temporal_jitter_ratio=0.15,
                 noise_sigma=0.03,
                 drop_joint_ratio=0.2,
                 use_mixup=False,
                 mixup_alpha=0.2,
                 flip_prob=0.5):
        self.debug = debug
        self.data_path = data_path
        self.label_path = label_path
        self.random_choose = random_choose
        self.random_move = random_move
        self.window_size = window_size
        self.layout = layout
        
        # 增强参数
        self.aug_prob = aug_prob
        self.rotation_range = rotation_range
        self.scale_range = scale_range
        self.translate_range = translate_range
        self.temporal_jitter_ratio = temporal_jitter_ratio
        self.noise_sigma = noise_sigma
        self.drop_joint_ratio = drop_joint_ratio
        self.use_mixup = use_mixup
        self.mixup_alpha = mixup_alpha
        self.flip_prob = flip_prob

        self.load_data(mmap)

    def load_data(self, mmap):
        # data: N C V T M

        # load label
        with open(self.label_path, 'rb') as f:
            self.sample_name, self.label = pickle.load(f)

        # load data
        if mmap:
            self.data = np.load(self.data_path, mmap_mode='r')
        else:
            self.data = np.load(self.data_path)
            
        if self.debug:
            self.label = self.label[0:100]
            self.data = self.data[0:100]
            self.sample_name = self.sample_name[0:100]

        self.N, self.C, self.T, self.V, self.M = self.data.shape

    def __len__(self):
        return len(self.label)

    def __getitem__(self, index):
        # get data
        data_numpy = np.array(self.data[index])
        label = self.label[index]
        
        # 基础处理
        if self.random_choose:
            data_numpy = tools.random_choose(data_numpy, self.window_size)
        elif self.window_size > 0:
            data_numpy = tools.auto_pading(data_numpy, self.window_size)
        
        if self.random_move:
            data_numpy = tools.random_move(data_numpy)
        
        # 数据增强（训练时应用）
        if random.random() < self.aug_prob:
            # 1. 随机旋转
            if random.random() < 0.6:
                data_numpy = tools.random_rotation(
                    data_numpy, angle_range=self.rotation_range)
            
            # 2. 随机缩放
            if random.random() < 0.6:
                data_numpy = tools.random_scaling(
                    data_numpy, scale_range=self.scale_range)
            
            # 3. 随机平移
            if random.random() < 0.6:
                data_numpy = tools.random_translation(
                    data_numpy, translate_range=self.translate_range)
            
            # 4. 时间抖动
            if random.random() < 0.5:
                data_numpy = tools.temporal_jitter(
                    data_numpy, jitter_ratio=self.temporal_jitter_ratio)
            
            # 5. 关节噪声
            if random.random() < 0.7:
                data_numpy = tools.joint_gaussian_noise(
                    data_numpy, sigma=self.noise_sigma)
            
            # 6. 左右镜像翻转
            if random.random() < self.flip_prob:
                data_numpy = tools.random_horizontal_flip(
                    data_numpy, layout=self.layout)
            
            # 7. 骨架遮挡/丢弃
            if random.random() < 0.4:
                data_numpy = tools.drop_joint(
                    data_numpy, drop_ratio=self.drop_joint_ratio)
        
        # 8. Mixup增强（可选，需要两个样本）
        if self.use_mixup and random.random() < 0.3:
            mixup_idx = random.randint(0, len(self.label) - 1)
            data_numpy2 = np.array(self.data[mixup_idx])
            label2 = self.label[mixup_idx]
            
            # 基础处理
            if self.random_choose:
                data_numpy2 = tools.random_choose(data_numpy2, self.window_size)
            elif self.window_size > 0:
                data_numpy2 = tools.auto_pading(data_numpy2, self.window_size)
            
            data_numpy, label = tools.skeleton_mixup(
                data_numpy, data_numpy2, label, label2, alpha=self.mixup_alpha)
            # Mixup后label是浮点数，需要转换为整数（取最近邻）
            label = int(np.round(label))

        return data_numpy, label






